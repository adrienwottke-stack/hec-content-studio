test('catalog only accepts known topics and source-bounded scene references',()=>{
  const raw={title:'Ein Testbild',category:'unsortiert',tags:['Testbild'],description:'Technisches Testbild.',moments:[{label:'Bild',from:1,duration:1,description:'Eine sichtbare Farbtafel.'}]};
  assert.equal(validateCatalog(raw,5).moments[0].from,1);
  assert.throws(()=>validateCatalog({...raw,category:'../../private'},5),/Einordnung/);
  assert.throws(()=>validateCatalog({...raw,moments:[{...raw.moments[0],from:5}]},5),/außerhalb/);
  assert.throws(()=>validateCatalog({...raw,moments:[{...raw.moments[0],duration:NaN}]},5),/außerhalb/);
  assert.equal(inferCatalog('IMG_001.mov').category,'unsortiert');
  assert.equal(inferCatalog('IMG_001.mov','Billard im Oktober').category,'billard');
  assert.equal(inferCatalog('IMG_001.mov').description,'');
  assert.throws(()=>libraryFields({recordedAt:'2026-02-31'}),/datum/i);
});
test('originals survive job deletion; duplicates, manual edits and references survive restart',async t=>{
  const dir=await fs.mkdtemp(path.join(scratch,'library-'));t.after(()=>fs.rm(dir,{recursive:true,force:true}));
  const jobs=new JobStore(dir);await jobs.initialize();const library=new MediaLibrary(dir);await library.initialize();
  const jobId=randomUUID(),assetId=randomUUID(),inputs=path.join(jobs.directory(jobId),'inputs');await fs.mkdir(inputs,{recursive:true});
  const source=path.join(inputs,'source.mov');await fs.writeFile(source,'fixture-original-content');
  await jobs.create({id:jobId,title:'Billard am Freitag',createdAt:new Date().toISOString(),status:'done',assets:[{id:assetId,name:'Original.mov',path:source,size:24}],options:{brief:''}});
  assert.equal((await library.importJobs(jobs)).length,1);
  const clip=library.get(assetId);assert.equal(clip.category,'billard');
  assert.equal((await library.importJobs(jobs)).length,0);
  const duplicated=await library.adopt({id:randomUUID(),name:'Andere Benennung.mov',path:source,size:24},{collection:'Zweite Sammlung'});
  assert.equal(duplicated.duplicate,true);assert.equal(duplicated.clip.id,assetId);assert.equal(library.list().length,1);
  await Promise.all([library.edit(assetId,{title:'Mein eigener Titel',favorite:true}),library.update(assetId,{description:'Automatische Beschreibung.'})]);
  await library.update(assetId,{title:'Anbietertitel',category:'events'});
  assert.equal(library.public(library.get(assetId)).title,'Mein eigener Titel');
  assert.equal(library.public(library.get(assetId)).favorite,true);
  assert.equal(library.public(library.get(assetId)).description,'Automatische Beschreibung.');
  await jobs.remove(jobId);
  assert.equal(await fs.readFile(library.get(assetId).path,'utf8'),'fixture-original-content');
  const restored=new MediaLibrary(dir);await restored.initialize();
  const publicClip=restored.public(restored.get(assetId));
  assert.equal(publicClip.reference,`footage:${assetId}`);assert.equal(publicClip.title,'Mein eigener Titel');
  assert.deepEqual(publicClip.collections,['Billard am Freitag','Zweite Sammlung']);
  assert.ok(!Object.hasOwn(publicClip,'path'));assert.ok(!Object.hasOwn(publicClip,'sha256'));
  assert.throws(()=>restored.directory('../secrets'),/Ungültige/);
});
test('simultaneous identical uploads keep one original and every collection after restart',async t=>{
  const dir=await fs.mkdtemp(path.join(scratch,'library-parallel-'));t.after(()=>fs.rm(dir,{recursive:true,force:true}));
  const library=new MediaLibrary(dir);await library.initialize();
  const source=path.join(dir,'source.mp4'),content=Buffer.from('same-original-from-multiple-uploads');await fs.writeFile(source,content);
  const sha256=await fileHash(source),save=library.save.bind(library);
  let releaseSave,firstSave;
  const gate=new Promise(resolve=>{releaseSave=resolve;}),saving=new Promise(resolve=>{firstSave=resolve;});
  library.save=async clip=>{firstSave();await gate;return save(clip);};
  const collections=['Billard','Freunde','Event-Footage'];
  const arrivals=collections.map((collection,index)=>library.adopt({id:randomUUID(),name:`Aufnahme-${index}.mp4`,path:source,size:content.length,sha256},{collection}));
  await saving;releaseSave();
  const results=await Promise.all(arrivals);
  assert.equal(new Set(results.map(result=>result.clip.id)).size,1);
  assert.equal(results.filter(result=>!result.duplicate).length,1);
  assert.equal(library.list().length,1);assert.equal(library.bytes(),content.length);
  assert.deepEqual([...library.list()[0].collections].sort(),[...collections].sort());
  const originals=(await fs.readdir(library.root,{withFileTypes:true})).filter(entry=>entry.isDirectory());assert.equal(originals.length,1);
  const restored=new MediaLibrary(dir);await restored.initialize();
  assert.equal(restored.list().length,1);
  assert.deepEqual([...restored.list()[0].collections].sort(),[...collections].sort());
  assert.deepEqual(await fs.readFile(restored.list()[0].path),content);
});
